def load_poi():
    d = json.load(open(os.path.join(DATA, 'schools-gz.json'), encoding='utf-8'))
    return d['schools'] if isinstance(d, dict) and 'schools' in d else d


def rec(name, group, feed, direct_feed, source_url, source_note, data_gaps=None):
    return {
        'name': name,
        'group': group,
        'feed_junior_highs': feed,
        'direct_feed': direct_feed,
        'source_url': source_url,
        'source_note': source_note,
        'data_gaps': data_gaps,
    }


def build_district(adcode, district_label, name_map, direct_map, no_feed, source_url, source_note, extra_note_fn=None):
    """通用构建。name_map: {官方组表小学名: [POI 名, ...]}；direct_map: {官方小学名: 直升初中}；
    no_feed: {POI名: 缺口说明}；extra_note_fn(official, poi_name) -> (feed, group, direct)。
    返回 (records, covered_poi_names, missing_poi_names)。"""
    poi = load_poi()
    district_poi = [s for s in poi if s['adcode'] == adcode]
    poi_by_name = {s['name']: s for s in district_poi}
    out = []
    covered = set()
    for official, poi_names in name_map.items():
        if not poi_names:
            print(f'  [{district_label}] 官方小学 POI 缺失（官方有、POI 无）: {official}')
            continue
        for pn in poi_names:
            if pn not in poi_by_name:
                print(f'  [{district_label}] 映射目标不存在于 POI: {pn}（来自 {official}）')
                continue
            if pn in covered:
                continue
            feed, group, direct = extra_note_fn(official, pn)
            out.append(rec(pn, group, feed, direct, source_url,
                           source_note + (f' {direct}面向对口直升。' if direct else ''),
                           None))
            covered.add(pn)
    # 未覆盖 POI → 缺口
    missing = []
    for pn in district_poi:
        if pn['name'] not in covered:
            if pn['name'] in no_feed:
                out.append(rec(pn['name'], '不参与公办电脑派位', [], None, source_url,
                               '民办/特殊教育/官方未单列。', no_feed[pn['name']]))
            else:
                missing.append(pn['name'])
    return out, covered, missing


