def build_tianhe():
    poi = load_poi()
    poi_names = {s['name'] for s in poi if s['adcode'] == '440106'}
    records = []
    covered = set()
    for official, vals in TH_MAP.items():
        for v in vals:
            if v not in poi_names:
                print(f'  [天河] 映射目标不存在于 POI: {v}（来自 {official}）')
    for official, vals in TH_MAP.items():
        if not vals:
            print(f'  [天河] 官方小学 POI 缺失: {official}（附件6 对口 {TH_FEED.get(official)}）')
            continue
        feed = TH_FEED.get(official)
        if feed is None:
            print(f'  [天河] 未定义对口初中的官方小学: {official}')
            continue
        if not feed:
            note = '2026年官方初中划片表未单列对口初中（2022年开办，2026年为首届毕业生），可自主报名附件10电脑派位。'
            gaps = '官方2026年划片表未单列对口初中，待区教育局补充。'
            group = '官方未单列（待核）'
        else:
            if official == '清华附中湾区学校（小学部）':
                group = '九年制学校内部直升（官方未单列小学部直升，按区属九年制直升惯例）+ 附件10全区电脑派位'
            elif official in ('智谷第一实验学校（小学部）', '广东实验中学天河学校（小学部）',
                              '天河外国语智谷学校（小学部）', '广州中学天河燕园学校（小学部）',
                              '华南理工大学附属实验学校（小学部）', '暨南大学附属实验学校（小学部）'):
                group = '九年制/企事业办学校小学部内部直升'
            else:
                group = f'天河区公办初中对口直升（{feed[0]}划片）'
            # 附件10 电脑派位资格
            paiwei = []
            for school, pool in TH_PAIWEI.items():
                if official in pool:
                    paiwei.append(school)
            note = '天河区单校划片，小学毕业生免试直升对口初中。'
            if paiwei:
                note += f' 另可自主报名附件10电脑派位：{"、".join(paiwei)}（报名人数超计划则电脑派位）。'
            if official == '清华附中湾区学校（小学部）':
                note += ' 九年制学校小学部毕业生直升本校初中部（官方附件6 未将清湾纳入划片，初中部面向全区自主报名电脑派位）。'
            elif len(feed) > 1:
                note += ' 官方划片表同时列出多所对口（见 source_note）。'
            gaps = None
        for pn in vals:
            if pn in covered:
                continue
            records.append(rec(pn, group, feed, None, TH_SRC, TH_NOTE + ' ' + note, gaps))
            covered.add(pn)
    missing = []
    for s in poi:
        if s['adcode'] != '440106':
            continue
        if s['name'] not in covered:
            if s['name'] in TH_NO_FEED:
                records.append(rec(s['name'], '不参与公办派位/待核', [], None, TH_SRC,
                                   '民办/特殊教育。', TH_NO_FEED[s['name']]))
            else:
                missing.append(s['name'])
    return records, covered, missing


