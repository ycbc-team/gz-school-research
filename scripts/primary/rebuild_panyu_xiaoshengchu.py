def apply(record, fix):
    name, group, feed, note = fix
    rec_name = record['name']
    x = record.get('xiaoshengchu') or {}
    x['group'] = group
    x['direct_feed'] = None
    x['feed_junior_highs'] = feed
    x['source_url'] = SRC_URL
    x['source_note'] = note
    record['xiaoshengchu'] = x

def main():
    targets = [
        os.path.join(ROOT, 'data/primary/tier1_schools_baiyun_huangpu_panyu.json'),
        os.path.join(ROOT, 'data/primary/tier1_schools_all.json'),
    ]
    for path in targets:
        d = json.load(open(path, encoding='utf-8'))
        schools = d['districts']['番禺区']['schools']
        patched = 0
        for fix in FIX:
            key = fix[0]
            # 匹配：名称包含 key（如"广东番禺中学附属学校"同时命中小学部与初中部，仅小学部有 xiaoshengchu）
            hit = [s for s in schools if key in s['name']]
            if not hit:
                print(f'  [WARN] 未匹配: {key}')
                continue
            for s in hit:
                if 'xiaoshengchu' not in s:
                    continue  # 只改带 xiaoshengchu 的记录（小学部）
                apply(s, fix)
                patched += 1
        json.dump(d, open(path, 'w', encoding='utf-8'), ensure_ascii=False, indent=2)
        print(f'{os.path.basename(path)}: patched={patched}/15')

if __name__ == '__main__':
    main()
