def clean(s):
    if not s: return None
    s2 = re.sub(r'[^\d]', '', str(s))
    return int(s2) if s2 else None

g = json.load(open(G)); sn = json.load(open(SN))
result = {}
for pno in sorted(g, key=int):
    pg = g[pno]
    names = sn.get(pno, [])
    if int(pno) not in PAGE_DISTRICT: continue
    cols = DISTRICT_COLS[PAGE_DISTRICT[int(pno)]]
    nrows = len(pg['rows']) // 2
    for r in range(nrows):
        name = names[r] if r < len(names) else ''
        if not name or re.match(r'^.{2,4}区$', name): continue
        row = {}
        for i, hn in enumerate(cols):
            v = clean(pg['data'].get(str(24 + i), {}).get(str(r), ''))
            if v: row[hn] = v
        if row:
            result[name] = row

json.dump({'updated': '2026', 'source': '2026年广州市普通高中名额分配结果（区属列）',
           'data': result}, open(OUT, 'w'), ensure_ascii=False, indent=1)
