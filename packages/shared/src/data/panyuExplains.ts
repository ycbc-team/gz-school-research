/** 把「(见)说明N」引用平铺为对应学段说明内容；未命中的说明号保留原文，避免误删。 */
export function expandPanyuNotes(note: string, stage: 'primary' | 'middle'): string {
  const explains = stage === 'primary' ? panyuPrimaryExplains : panyuMiddleExplains;
  return note.replace(/见?说明(\d+)/g, (m, n: string) => explains[Number(n)] ?? m);
}
