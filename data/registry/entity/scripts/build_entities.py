# （如「广州中学」→「中学」）时保留前缀，避免泛词毁名（历史多次踩坑）。
BARE_GENERIC = {'中学', '小学', '学校', '幼儿园', '实验中学', '实验学校', '中心小学', '第一小学', '实验小学', '附属小学', '附属中学'}
BARE_DISTRICT = re.compile(r'^(荔湾|越秀|海珠|天河|白云|黄埔|番禺)区')
_BARE_PAREN = re.compile(r'\([^()]*\)')


def bareCoreOf(rawNorm):
    bc = _BARE_PAREN.sub('', rawNorm)
    bc = re.sub(r'^广州市', '', bc)
    bc = BARE_DISTRICT.sub('', bc)
    if bc.startswith('广州') and bc[2:] not in BARE_GENERIC:
        bc = bc[2:]
    return bc


def _half(s):
    """全角括号→半角 + 去空白（bareCore 统计用原始规范化，保留括号结构；与 normName 语义不同）。"""
    return re.sub(r'\s+', '', str(s).replace('（', '(').replace('）', ')'))


