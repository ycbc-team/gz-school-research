def attachAlias(stage, poiName, aliasName, force=False):
    ent = entByStagePoiName.get(stage + '|' + normName(poiName))
    # 跨 stage fallback：官方名指向完中实体（如广附黄华路 stage=middle，但官方录取表
    # 按「广州大学附属中学」招生，应把别名挂到该实体，由匹配器按实体全量索引命中）
    if ent is None:
        for k, e in entByStagePoiName.items():
            if k.endswith('|' + normName(poiName)):
                ent = e
                break
    if ent is None:
        return False
    for v in withDistrictVariants(normName(aliasName)):
        # 纯名变体先占先得：已被同 stage 同名主校区实体持有则跳过，避免同区纯名被多实体共用
        # （官方主名「广州市白云区景泰中学」的纯名变体「景泰中学」属于主校区实体，不再挂到白云湖校区）
        if isPlainAlias(v):
            key = ent['school_id'].split('-')[1] + '|' + v
            owner = plainOwner.get(key)
            if owner and owner != ent['school_id']:
                # force=显式人工配置（OFFICIAL_HIGH_ALIAS 官方录取表名等）：绕过纯名拦截。
                # 官方录取分数表用裸名招生（如「广州市第一一三中学」「广州大学附属中学」），
                # 纯名拦截会阻止其挂到 high 实体（如一一三中金融城/元岗两校区、广大附大学城），导致录取分落 unmapped。
                # 显式配置表达"该裸名属于这些实体"的明确意图，不受纯名先占规则约束。
                if not force:
                    continue
            plainOwner[key] = ent['school_id']
        if v == normName(ent['name']):
            continue  # 自身归一名不入 aliases（索引侧 name 已覆盖）
        alias_add(ent['aliases'], v)
    return True


