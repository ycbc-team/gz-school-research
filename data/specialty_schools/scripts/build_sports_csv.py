    if school_name in KNOWN:
        return KNOWN[school_name]
    for d in DISTRICTS:
        if d in school_name:
            return d
    if "从化" in school_name:
        return "从化区"
    if "增城" in school_name:
        return "增城区"
    return "区推断"

